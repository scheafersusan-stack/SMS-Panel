// Builds src/icons/icons.gen.ts from the design-system SVGs in src/icons: keeps only the shape
// elements (drops the fixed stroke colour and the C2PA metadata) so icons follow currentColor.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "icons");
const entries = readdirSync(dir)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((f) => {
    const src = readFileSync(join(dir, f), "utf8");
    const inner = src
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<metadata>[\s\S]*?<\/metadata>/, "")
      .replace(/<\/svg>\s*$/, "")
      .trim();
    return `  ${JSON.stringify(f.slice(0, -4))}: ${JSON.stringify(inner)},`;
  });
writeFileSync(
  join(dir, "icons.gen.ts"),
  `// Generated by scripts/gen-icons.mjs (npm run icons). Do not edit.\nexport const ICONS: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
